"""Summary of the supplementary 2000-episode runs (results/long_eval.csv) on the test split.

Writes results/long_summary.csv and results/long_summary.md: geomean size reduction vs -O0,
wins/ties/losses against -O2, -O3, -Oz and the best fixed sequence, distinct greedy
sequences, policy entropy at the start and end of training, and the selected checkpoint.
Same conventions as scripts/analyze.py.
"""
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from rlpo.io import save_csv  # noqa: E402

ev = pd.read_csv("results/long_eval.csv")
base = pd.read_csv("results/baselines.csv").set_index("benchmark")
best = pd.read_csv("results/sanity_baselines.csv").set_index("benchmark").best_fixed


def wtl(a, b):
    return f"{int((a < b).sum())}/{int((a == b).sum())}/{int((a > b).sum())}"


rows = []
for run, g in ev.groupby("run"):
    t = g[g.split == "test"]
    b = base.loc[t.benchmark]
    final = t.final.where(t.final.notna(), b.O0.values).values  # a crash counts as no reduction
    log = pd.read_csv(os.path.join("runs", run, "train_log.csv"))
    meta = json.load(open(os.path.join("runs", run, "run.json")))
    rows.append({
        "run": run, "reward": meta["reward"], "episodes": meta["episodes"], "test programs": len(t),
        "test reduction": round(1 - float(np.exp(np.mean(np.log(final / b.O0.values)))), 4),
        "vs -O2": wtl(final, b.O2.values), "vs -O3": wtl(final, b.O3.values), "vs -Oz": wtl(final, b.Oz.values),
        "vs best fixed": wtl(final, best.loc[t.benchmark].values),
        "distinct greedy seqs (all/test)": f"{g.sequence.nunique()}/{t.sequence.nunique()}",
        "entropy first": round(float(log.entropy.iloc[0]), 2), "entropy last": round(float(log.entropy.iloc[-1]), 2),
        "selected checkpoint": meta["selected"], "replay ok": f"{int(g.replay_ok.sum())}/{len(g)}",
    })
out = pd.DataFrame(rows)
save_csv(out, "results/long_summary.csv")
cols = list(out.columns)
md = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
md += ["| " + " | ".join(str(v) for v in r) + " |" for r in out.itertuples(index=False)]
with open("results/long_summary.md", "w") as fh:
    fh.write("# Supplementary 2000-episode runs (generated by scripts/supplementary.py)\n\n" + "\n".join(md) + "\n")
print(out.to_string(index=False))
